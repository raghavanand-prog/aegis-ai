"""AI analyst, threat intelligence and degraded-mode evaluation.

Three subsystems that cannot be scored with a confusion matrix, evaluated on
what can actually be measured about them rather than on how convincing their
output reads.

AI analyst
----------

Prose quality is not evaluated, because it is not the property that matters and
because judging it would need a judge whose own reliability is unestablished.
What is measured is whether the analysis is **anchored to the evidence it was
given**, using the production grounding verifier:

* grounding rate - analyses with no grounding warning
* unsupported-technique rate - MITRE techniques cited that the evidence package
  does not contain, with matching provenance
* unresolved-reference rate - supporting-evidence references resolving to
  nothing
* confidence behaviour - whether ``high`` confidence is claimed on evidence the
  package itself declares insufficient
* injection resistance - whether a prompt-injection string planted in event
  data changes the verdict
* latency

Every result is labelled with the provider that produced it. Runs against the
built-in deterministic template provider are labelled **mock**, and a mock
result is a test of the pipeline - evidence assembly, sanitization, grounding,
persistence - not evidence about any language model's behaviour.

Threat intelligence
-------------------

Only measurable where real data exists. The synthetic corpus uses RFC 5737
documentation ranges, which the SSRF validator refuses by design, so there is
nothing to enrich and this evaluation reports the refusals rather than
pretending an enrichment happened. With no provider configured, the honest
output is a stated absence.

Degraded mode
-------------

The V3 architectural guarantee is that an optional subsystem failing must not
become an ingestion failure. That is testable directly: disable or break each
optional subsystem, push telemetry through, and assert that events still
normalize, rules still fire, and the surface states a reason rather than going
blank.
"""

